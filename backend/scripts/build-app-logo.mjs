function cubic(start, c1, c2, end) {
  for (let i = 1; i <= 100; i++) {
    const t = i / 100, u = 1 - t;
    points.push([0, 1].map((axis) => (u ** 3 * start[axis] + 3 * u ** 2 * t * c1[axis] + 3 * u * t ** 2 * c2[axis] + t ** 3 * end[axis]) / 4));
  }
}
