import { deflateSync } from "node:zlib";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SIZE = 128;
const rgba = Buffer.alloc(SIZE * SIZE * 4);
const points = [];

// Ionicons' water-outline silhouette, sampled as a polyline and rendered with
// rounded joins. Keeping the tiny renderer here makes this asset reproducible
// without a native image dependency.
for (let i = 0; i <= 80; i += 1) {
  const t = i / 80;
  const y = 13 + (96 * t);
  const halfWidth = 49 * Math.sin(Math.PI * t) * (0.65 + (0.35 * t));
  points.push([64 - halfWidth, y]);
}
for (let i = 80; i >= 0; i -= 1) {
  const t = i / 80;
  const y = 13 + (96 * t);
  const halfWidth = 49 * Math.sin(Math.PI * t) * (0.65 + (0.35 * t));
  points.push([64 + halfWidth, y]);
}

function distanceToSegment(px, py, [ax, ay], [bx, by]) {
  const dx = bx - ax;
  const dy = by - ay;
  const lengthSquared = (dx * dx) + (dy * dy);
  const t = lengthSquared ? Math.max(0, Math.min(1, (((px - ax) * dx) + ((py - ay) * dy)) / lengthSquared)) : 0;
  return Math.hypot(px - (ax + (t * dx)), py - (ay + (t * dy)));
}

for (let y = 0; y < SIZE; y += 1) {
  for (let x = 0; x < SIZE; x += 1) {
    let distance = Infinity;
    for (let i = 1; i < points.length; i += 1) {
      distance = Math.min(distance, distanceToSegment(x + 0.5, y + 0.5, points[i - 1], points[i]));
    }
    const alpha = Math.round(255 * Math.max(0, Math.min(1, 3.5 - distance)));
    const offset = ((y * SIZE) + x) * 4;
    rgba.set([0x24, 0xc4, 0xcd, alpha], offset);
  }
}

function chunk(type, data) {
  const typeBuffer = Buffer.from(type);
  const body = Buffer.concat([typeBuffer, data]);
  let crc = 0xffffffff;
  for (const byte of body) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit += 1) crc = (crc >>> 1) ^ (0xedb88320 & -(crc & 1));
  }
  const trailer = Buffer.alloc(4);
  trailer.writeUInt32BE((crc ^ 0xffffffff) >>> 0);
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  return Buffer.concat([length, body, trailer]);
}

const header = Buffer.alloc(13);
header.writeUInt32BE(SIZE, 0);
header.writeUInt32BE(SIZE, 4);
header.set([8, 6, 0, 0, 0], 8);
const scanlines = Buffer.concat(Array.from({ length: SIZE }, (_, y) =>
  Buffer.concat([Buffer.from([0]), rgba.subarray(y * SIZE * 4, (y + 1) * SIZE * 4)])));
const png = Buffer.concat([
  Buffer.from("89504e470d0a1a0a", "hex"),
  chunk("IHDR", header),
  chunk("IDAT", deflateSync(scanlines, { level: 9 })),
  chunk("IEND", Buffer.alloc(0)),
]);

const here = dirname(fileURLToPath(import.meta.url));
const output = resolve(here, "../src/documents/assets/logoAppDrop.js");
await mkdir(dirname(output), { recursive: true });
await writeFile(output, `// Generated by scripts/build-app-logo.mjs.\nexport const LOGO_APP_DROP_BASE64 = "${png.toString("base64")}";\n`);
console.log(`Wrote ${output}`);
